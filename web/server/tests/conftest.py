def sha(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest() if Path(p).exists() else "missing"


def frozen_hashes() -> dict[str, str]:
    return {p.name: sha(p) for p in FROZEN}


